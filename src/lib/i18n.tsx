type Lang = 'vi' | 'en';
interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string; err: (e: unknown) => string }
const I18n = createContext<Ctx | null>(null);

const readLang = (): Lang => {
  try {
    const s = localStorage.getItem('onquiz.lang');
    if (s === 'vi' || s === 'en') return s;
  } catch { /* storage có thể bị chặn */ }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'vi';
};

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('onquiz.lang', l); } catch { /* ignore */ }
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<Ctx>(() => {
    const dict: Record<Key, string> = lang === 'vi' ? vi : en;
    const t: Ctx['t'] = (k, vars) =>
      Object.entries(vars ?? {}).reduce((s, [a, b]) => s.replace(`{${a}}`, String(b)), dict[k]);
    const err = (e: unknown) => {
      const m = e instanceof Error ? e.message : String(e);
      const key = `err.${m}` as Key;
      return key in dict ? dict[key] : dict['common.error'];
    };
    return { lang, setLang, t, err };
  }, [lang, setLang]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18n);
  if (!c) throw new Error('I18nProvider missing');
  return c;
}
